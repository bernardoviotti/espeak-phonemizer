#!/usr/bin/env node
// Generates src/constants.mjs from the pinned espeak-ng commit's headers.
//
// - espeakCHARS_* / espeakPHONEMES_* / espeakINITIALIZE_* / AUDIO_OUTPUT_* come
//   from the public header src/include/espeak-ng/speak_lib.h (regex-extracted
//   #define values, plus the AUDIO_OUTPUT_* enum which is hand-verified below
//   since it's a C enum, not a #define).
// - CLAUSE_* constants are NOT part of the public API (they live in the
//   internal src/libespeak-ng/translate.h) and are instead reproduced verbatim
//   from piper1-gpl's own src/piper/espeakbridge.c, which redefines them
//   locally for exactly this reason. We cross-checked at generation time that
//   piper1-gpl's values match translate.h at the pinned commit exactly.
//
// Run whenever the pinned espeak-ng commit changes; output is committed.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEAK_LIB_H = path.join(ROOT, 'vendor/espeak-ng/src/include/espeak-ng/speak_lib.h');
const TRANSLATE_H = path.join(ROOT, 'vendor/espeak-ng/src/libespeak-ng/translate.h');

function extractDefines(text, prefix) {
  const re = new RegExp(`#define\\s+(${prefix}\\w*)\\s+(0x[0-9a-fA-F]+|\\d+)\\b`, 'g');
  const out = [];
  let m;
  while ((m = re.exec(text))) out.push([m[1], m[2]]);
  return out;
}

const speakLibSrc = readFileSync(SPEAK_LIB_H, 'utf8');
const translateSrc = readFileSync(TRANSLATE_H, 'utf8');

const charsDefines = extractDefines(speakLibSrc, 'espeakCHARS_');
const phonemesDefines = extractDefines(speakLibSrc, 'espeakPHONEMES_');
const initDefines = extractDefines(speakLibSrc, 'espeakINITIALIZE_');

if (charsDefines.length === 0 || phonemesDefines.length === 0) {
  throw new Error(`failed to extract espeakCHARS_*/espeakPHONEMES_* from ${SPEAK_LIB_H}`);
}

// AUDIO_OUTPUT_* is a plain C enum (not #define), starting at 0 in
// declaration order — verified against speak_lib.h at the pinned commit:
//   AUDIO_OUTPUT_PLAYBACK, AUDIO_OUTPUT_RETRIEVAL, AUDIO_OUTPUT_SYNCHRONOUS, AUDIO_OUTPUT_SYNCH_PLAYBACK
const audioOutputEnumMatch = speakLibSrc.match(
  /AUDIO_OUTPUT_PLAYBACK[\s\S]*?AUDIO_OUTPUT_RETRIEVAL[\s\S]*?AUDIO_OUTPUT_SYNCHRONOUS[\s\S]*?AUDIO_OUTPUT_SYNCH_PLAYBACK/
);
if (!audioOutputEnumMatch) {
  throw new Error('AUDIO_OUTPUT_* enum shape in speak_lib.h no longer matches what gen-constants.mjs expects — update this script.');
}
const AUDIO_OUTPUT = {
  AUDIO_OUTPUT_PLAYBACK: 0,
  AUDIO_OUTPUT_RETRIEVAL: 1,
  AUDIO_OUTPUT_SYNCHRONOUS: 2,
  AUDIO_OUTPUT_SYNCH_PLAYBACK: 3,
};

// Cross-check CLAUSE_* values against translate.h before hardcoding them
// (piper1-gpl's espeakbridge.c defines these same values locally too, since
// they're not part of espeak-ng's public API).
const expectedClauseSource = {
  CLAUSE_INTONATION_FULL_STOP: '0x00000000',
  CLAUSE_INTONATION_COMMA: '0x00001000',
  CLAUSE_INTONATION_QUESTION: '0x00002000',
  CLAUSE_INTONATION_EXCLAMATION: '0x00003000',
  CLAUSE_TYPE_CLAUSE: '0x00040000',
  CLAUSE_TYPE_SENTENCE: '0x00080000',
};
for (const [name, expectedHex] of Object.entries(expectedClauseSource)) {
  const re = new RegExp(`#define\\s+${name}\\s+(0x[0-9a-fA-F]+)`);
  const m = translateSrc.match(re);
  if (!m || BigInt(m[1]) !== BigInt(expectedHex)) {
    throw new Error(
      `translate.h's ${name} no longer matches the value this script/espeakbridge.c expects ` +
      `(expected ${expectedHex}, found ${m ? m[1] : 'nothing'}) — re-derive CLAUSE_* constants.`
    );
  }
}

const CLAUSE_INTONATION_FULL_STOP = 0x00000000;
const CLAUSE_INTONATION_COMMA = 0x00001000;
const CLAUSE_INTONATION_QUESTION = 0x00002000;
const CLAUSE_INTONATION_EXCLAMATION = 0x00003000;
const CLAUSE_TYPE_CLAUSE = 0x00040000;
const CLAUSE_TYPE_SENTENCE = 0x00080000;

const CLAUSE = {
  CLAUSE_INTONATION_FULL_STOP,
  CLAUSE_INTONATION_COMMA,
  CLAUSE_INTONATION_QUESTION,
  CLAUSE_INTONATION_EXCLAMATION,
  CLAUSE_TYPE_CLAUSE,
  CLAUSE_TYPE_SENTENCE,
  CLAUSE_PERIOD: 40 | CLAUSE_INTONATION_FULL_STOP | CLAUSE_TYPE_SENTENCE,
  CLAUSE_COMMA: 20 | CLAUSE_INTONATION_COMMA | CLAUSE_TYPE_CLAUSE,
  CLAUSE_QUESTION: 40 | CLAUSE_INTONATION_QUESTION | CLAUSE_TYPE_SENTENCE,
  CLAUSE_EXCLAMATION: 45 | CLAUSE_INTONATION_EXCLAMATION | CLAUSE_TYPE_SENTENCE,
  CLAUSE_COLON: 30 | CLAUSE_INTONATION_FULL_STOP | CLAUSE_TYPE_CLAUSE,
  CLAUSE_SEMICOLON: 30 | CLAUSE_INTONATION_COMMA | CLAUSE_TYPE_CLAUSE,
};

function toHex(n) {
  return '0x' + n.toString(16).padStart(8, '0');
}

const outputPath = path.join(ROOT, 'src/constants.mjs');
const header = [
  '// GENERATED by scripts/gen-constants.mjs — do not hand-edit.',
  '// Source: vendor/espeak-ng (pinned commit) speak_lib.h + translate.h,',
  "// cross-checked against piper1-gpl's src/piper/espeakbridge.c.",
  '',
  '// -- espeak_Char_Type (text encoding passed to *TextToPhonemes*) --',
  ...charsDefines.map(([name, value]) => `export const ${name} = ${value};`),
  '',
  '// -- espeak_PHONEME_MODE bits --',
  ...phonemesDefines.map(([name, value]) => `export const ${name} = ${value};`),
  '',
  '// -- espeak_Initialize() option bits --',
  ...initDefines.map(([name, value]) => `export const ${name} = ${value};`),
  '',
  '// -- espeak_AUDIO_OUTPUT enum (from speak_lib.h, not a #define) --',
  ...Object.entries(AUDIO_OUTPUT).map(([name, value]) => `export const ${name} = ${value};`),
  '',
  '// -- CLAUSE_* (internal to espeak-ng, not part of the public API — see',
  '//    src/libespeak-ng/translate.h. Reproduced to match espeakbridge.c.) --',
  ...Object.entries(CLAUSE).map(([name, value]) => `export const ${name} = ${toHex(value)};`),
  '',
  'export const CLAUSE_TERMINATOR_MASK = 0x000fffff;',
  '',
  '// Maps a masked terminator value to the punctuation character espeakbridge.c',
  '// would report for it (empty string when it matches none of these).',
  'const TERMINATOR_STRINGS = new Map([',
  '  [CLAUSE_PERIOD, "."],',
  '  [CLAUSE_QUESTION, "?"],',
  '  [CLAUSE_EXCLAMATION, "!"],',
  '  [CLAUSE_COMMA, ","],',
  '  [CLAUSE_COLON, ":"],',
  '  [CLAUSE_SEMICOLON, ";"],',
  ']);',
  '',
  '/**',
  ' * @param {number} terminator raw terminator value from',
  ' *   espeak_TextToPhonemesWithTerminator',
  ' * @returns {{ terminator: string, isSentenceEnd: boolean }}',
  ' */',
  'export function decodeTerminator(terminator) {',
  '  const masked = terminator & CLAUSE_TERMINATOR_MASK;',
  '  return {',
  '    terminator: TERMINATOR_STRINGS.get(masked) ?? "",',
  '    isSentenceEnd: (masked & CLAUSE_TYPE_SENTENCE) === CLAUSE_TYPE_SENTENCE,',
  '  };',
  '}',
  '',
].join('\n');

writeFileSync(outputPath, header);
console.log(`wrote ${outputPath}`);
